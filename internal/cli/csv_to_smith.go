package cli

import (
	"encoding/csv"
	"fmt"
	"io"
	"os"
	"strconv"
	"strings"
)

func runCSVToSmith(args []string, out, stderr io.Writer) int {
	if len(args) == 0 {
		fmt.Fprintln(stderr, "usage: qasmith csv-to-smith <input.csv> [-o output.smith]")
		return 2
	}

	inputPath := args[0]
	outputPath := ""

	// Parse optional flags
	for i := 1; i < len(args); i++ {
		if args[i] == "-o" && i+1 < len(args) {
			outputPath = args[i+1]
			i++
		} else {
			fmt.Fprintf(stderr, "unknown option: %s\n", args[i])
			return 2
		}
	}

	// Generate output path if not specified
	if outputPath == "" {
		outputPath = strings.TrimSuffix(inputPath, ".csv") + ".smith"
	}

	// Read and convert CSV
	code, err := csvToSmith(inputPath)
	if err != nil {
		fmt.Fprintf(stderr, "error: %v\n", err)
		return 1
	}

	// Write output
	if err := os.WriteFile(outputPath, []byte(code), 0644); err != nil {
		fmt.Fprintf(stderr, "error writing output file: %v\n", err)
		return 1
	}

	fmt.Fprintf(out, "Generated %s from %s\n", outputPath, inputPath)
	return 0
}

func csvToSmith(path string) (string, error) {
	file, err := os.Open(path)
	if err != nil {
		return "", fmt.Errorf("failed to open CSV file: %w", err)
	}
	defer file.Close()

	reader := csv.NewReader(file)
	reader.Comment = '#'
	reader.TrimLeadingSpace = true

	var distances [][]float64
	lineNum := 0

	for {
		record, err := reader.Read()
		if err == io.EOF {
			break
		}
		if err != nil {
			return "", fmt.Errorf("failed to read CSV line %d: %w", lineNum+1, err)
		}

		lineNum++

		// Skip empty lines and comments
		if len(record) == 0 || (len(record) == 1 && strings.TrimSpace(record[0]) == "") {
			continue
		}

		var row []float64
		for i, field := range record {
			value, err := strconv.ParseFloat(strings.TrimSpace(field), 64)
			if err != nil {
				return "", fmt.Errorf("failed to parse distance at row %d, col %d (%q): %w", lineNum, i+1, field, err)
			}
			row = append(row, value)
		}

		// Validate matrix is square
		if len(distances) > 0 && len(row) != len(distances[0]) {
			return "", fmt.Errorf("CSV is not a square matrix: row %d has %d columns, expected %d", lineNum, len(row), len(distances[0]))
		}

		distances = append(distances, row)
	}

	if len(distances) < 3 {
		return "", fmt.Errorf("distance matrix must have at least 3 cities, got %d", len(distances))
	}

	// Generate Smith code
	var sb strings.Builder
	sb.WriteString("// Generated from CSV file: " + path + "\n")
	sb.WriteString("// Number of cities: " + strconv.Itoa(len(distances)) + "\n")
	sb.WriteString("//\n")
	sb.WriteString("// This file was generated by: qasmith csv-to-smith " + path + "\n")
	sb.WriteString("//\n")
	sb.WriteString("// Run with: qasmith run " + strings.TrimSuffix(path, ".csv") + ".smith\n\n")
	sb.WriteString("import { tsp } from \"std/optimization/tsp\";\n")
	sb.WriteString("import { qaoa } from \"std/optimization/qaoa\";\n\n")
	sb.WriteString("fn main() -> MeasuredResult {\n")
	sb.WriteString("    let distances = [\n")

	for i, row := range distances {
		sb.WriteString("        [")
		for j, val := range row {
			if j > 0 {
				sb.WriteString(", ")
			}
			// Always use float format for consistency
			sb.WriteString(fmt.Sprintf("%.2f", val))
		}
		sb.WriteString("]")
		if i < len(distances)-1 {
			sb.WriteString(",")
		}
		sb.WriteString("\n")
	}

	sb.WriteString("    ];\n\n")
	sb.WriteString("    let problem = tsp(distances, 0);\n")
	sb.WriteString("    return qaoa(problem, [0.4], [0.3]);\n")
	sb.WriteString("}\n")

	return sb.String(), nil
}
