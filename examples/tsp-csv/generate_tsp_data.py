#!/usr/bin/env python3
"""
Generate a realistic 50-city TSP distance matrix with coordinates.
Cities are placed in a 2D plane and distances are calculated using Euclidean distance.
"""

import csv
import math
import random

# Set seed for reproducibility
random.seed(42)

# Number of cities
NUM_CITIES = 50

# Generate random city coordinates in a 1000x1000 grid
cities = []
for i in range(NUM_CITIES):
    x = random.uniform(0, 1000)
    y = random.uniform(0, 1000)
    cities.append((x, y))

# Calculate Euclidean distance matrix
def euclidean_distance(c1, c2):
    return math.sqrt((c1[0] - c2[0])**2 + (c1[1] - c2[1])**2)

# Write coordinates CSV
with open('cities.csv', 'w', newline='') as f:
    writer = csv.writer(f)
    writer.writerow(['id', 'x', 'y'])
    for i, (x, y) in enumerate(cities):
        writer.writerow([i, f'{x:.2f}', f'{y:.2f}'])

# Write distance matrix CSV
with open('distances_50.csv', 'w', newline='') as f:
    f.write(f'# Distance matrix for {NUM_CITIES} cities\n')
    f.write('# Distances are Euclidean distances between city coordinates\n')
    f.write('# Generated by generate_tsp_data.py\n')
    
    writer = csv.writer(f)
    for i in range(NUM_CITIES):
        row = []
        for j in range(NUM_CITIES):
            if i == j:
                row.append(0)
            else:
                dist = euclidean_distance(cities[i], cities[j])
                row.append(f'{dist:.2f}')
        writer.writerow(row)

print(f"Generated {NUM_CITIES} cities")
print(f"Coordinates saved to: cities.csv")
print(f"Distance matrix saved to: distances_50.csv")

# Also create smaller versions for testing
for n in [10, 20, 30]:
    subset = cities[:n]
    with open(f'distances_{n}.csv', 'w', newline='') as f:
        f.write(f'# Distance matrix for {n} cities\n')
        writer = csv.writer(f)
        for i in range(n):
            row = []
            for j in range(n):
                if i == j:
                    row.append(0)
                else:
                    dist = euclidean_distance(subset[i], subset[j])
                    row.append(f'{dist:.2f}')
            writer.writerow(row)
    print(f"Created {n}-city matrix: distances_{n}.csv")
