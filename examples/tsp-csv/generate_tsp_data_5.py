#!/usr/bin/env python3
"""
Generate a realistic 5-city TSP distance matrix with coordinates.
This is within the 16-qubit simulator limit.
"""

import csv
import math
import random

# Set seed for reproducibility
random.seed(123)

# Number of cities (max 5 for 16-qubit simulator: (5-1)^2 = 16 qubits)
NUM_CITIES = 5

# Generate random city coordinates in a 1000x1000 grid
cities = []
for i in range(NUM_CITIES):
    x = random.uniform(0, 1000)
    y = random.uniform(0, 1000)
    cities.append((x, y))

# Calculate Euclidean distance matrix
def euclidean_distance(c1, c2):
    return math.sqrt((c1[0] - c2[0])**2 + (c1[1] - c2[1])**2)

# Write coordinates CSV
with open('cities_5.csv', 'w', newline='') as f:
    writer = csv.writer(f)
    writer.writerow(['id', 'name', 'x', 'y'])
    city_names = ['New York', 'Los Angeles', 'Chicago', 'Houston', 'Phoenix']
    for i, (x, y) in enumerate(cities):
        writer.writerow([i, city_names[i], f'{x:.2f}', f'{y:.2f}'])

# Write distance matrix CSV
with open('distances_5.csv', 'w', newline='') as f:
    f.write(f'# Distance matrix for {NUM_CITIES} cities\n')
    f.write('# Distances are Euclidean distances between city coordinates\n')
    f.write('# Generated by generate_tsp_data_5.py\n')
    
    writer = csv.writer(f)
    for i in range(NUM_CITIES):
        row = []
        for j in range(NUM_CITIES):
            if i == j:
                row.append(0.0)
            else:
                dist = euclidean_distance(cities[i], cities[j])
                row.append(f'{dist:.2f}')
        writer.writerow(row)

print(f"Generated {NUM_CITIES} cities")
print(f"Coordinates saved to: cities_5.csv")
print(f"Distance matrix saved to: distances_5.csv")
print(f"\nQubit requirement: ({NUM_CITIES}-1)^2 = {(NUM_CITIES-1)**2} qubits")
print(f"Simulator limit: 16 qubits")
print(f"Status: {'✓ Within limit' if (NUM_CITIES-1)**2 <= 16 else '✗ Exceeds limit'}")

# Calculate optimal tour using brute force for verification
import itertools

def calculate_tour_distance(tour, distances):
    total = 0
    for i in range(len(tour)):
        total += distances[tour[i]][tour[(i+1) % len(tour)]]
    return total

# Read distances
distances = []
with open('distances_5.csv', 'r') as f:
    for line in f:
        if line.startswith('#'):
            continue
        distances.append([float(x) for x in line.strip().split(',')])

# Find optimal tour
cities_list = list(range(NUM_CITIES))
optimal_tour = None
optimal_distance = float('inf')

for perm in itertools.permutations(cities_list):
    dist = calculate_tour_distance(perm, distances)
    if dist < optimal_distance:
        optimal_distance = dist
        optimal_tour = perm

print(f"\nOptimal tour (classical): {optimal_tour}")
print(f"Optimal distance: {optimal_distance:.2f}")
